/**
 * MPI AI Capability Registry & Modular Orchestration Architecture
 *
 * Implements the official 62-capability blueprint across 6 core pillars:
 * 1. Demand capture and procurement intake
 * 2. Supplier discovery and MSME enablement
 * 3. RFQ, quotation and commercial comparison
 * 4. Schemes, compliance and business navigation
 * 5. Analytics, forecasting, risk and performance
 * 6. Copilots, workflow and trust
 *
 * Architectural Principle:
 * Separates existing working AI capabilities (available/beta) from future roadmap capabilities (planned).
 * Ensures deterministic structured output, calibrated confidence ratings, and strict human authorization gates.
 */

export type AICapabilityCategory =
  | "demand_capture"
  | "supplier_discovery"
  | "rfq_quotation"
  | "schemes_compliance"
  | "analytics_forecasting"
  | "copilots_trust"

export type AICapabilityStatus = "available" | "beta" | "prototype" | "planned" | "deprecated"

export type UserRole = "public" | "startup" | "msme" | "admin"

export type EvidenceSourceType = "verified_data" | "supplier_declared" | "estimated" | "ai_inference"

export interface AIEvidenceItem {
  factor: string
  type: EvidenceSourceType
  description: string
}

export interface AIConfidenceRating {
  score: number // 0.0 to 1.0
  level: "High confidence" | "Needs confirmation" | "Insufficient evidence"
  explanation?: string
}

export interface AINextAction {
  action: string
  label: string
  targetScreen?: string
  payload?: Record<string, unknown>
}

/**
 * Mandatory Structured Output Contract (Section 5)
 */
export interface AIStandardOutput<T = unknown> {
  status: "success" | "partial" | "needs_input" | "failed"
  result: T
  confidence: AIConfidenceRating
  missing_information: string[]
  evidence: AIEvidenceItem[]
  warnings: string[]
  next_action?: AINextAction
}

