/**
 * Capability Discovery Helpers
 */
export function getCapabilityById(id: string): AICapabilityDefinition | undefined {
  return MPI_AI_CAPABILITIES[id]
}

export function getCapabilitiesByCategory(category: AICapabilityCategory): AICapabilityDefinition[] {
  return Object.values(MPI_AI_CAPABILITIES).filter((cap) => cap.category === category)
}

export function getAvailableCapabilities(): AICapabilityDefinition[] {
  return Object.values(MPI_AI_CAPABILITIES).filter((cap) => cap.status === "available" || cap.status === "beta")
}

export function getPlannedRoadmapCapabilities(): AICapabilityDefinition[] {
  return Object.values(MPI_AI_CAPABILITIES).filter((cap) => cap.status === "planned")
}

/**
 * Standardized AI Output Factory (Section 5)
 */
export function createStandardAIOutput<T>(
  status: AIStandardOutput<T>["status"],
  result: T,
  confidenceScore: number,
  options: {
    missing_information?: string[]
    evidence?: AIEvidenceItem[]
    warnings?: string[]
    next_action?: AINextAction
  } = {},
): AIStandardOutput<T> {
  const score = Math.max(0, Math.min(1, confidenceScore))
  let level: AIConfidenceRating["level"] = "Insufficient evidence"
  if (score >= 0.8) {
    level = "High confidence"
  } else if (score >= 0.5) {
    level = "Needs confirmation"
  }

  return {
    status,
    result,
    confidence: {
      score,
      level,
    },
    missing_information: options.missing_information || [],
    evidence: options.evidence || [],
    warnings: options.warnings || [],
    next_action: options.next_action,
  }
}
